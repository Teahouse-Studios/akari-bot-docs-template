import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import type { AcceptedPlugin } from "postcss";
import type { Plugin } from "vite";

import { AKARI_BOOT_CONTROL_SCRIPT, akariBootPageStyle, injectAkariBoot } from "./boot";
import { akariBootColors } from "./bootColors";
import { akariMediaColors, type AkariMediaColorsPlugin } from "./media-colors";
import { akariMediaWebp, type BuiltSite } from "./media-webp";

/**
 * The plugins and hooks the theme needs while a site is built.
 *
 * A site generated by the CLI writes its own VitePress config, so the theme
 * cannot put these in its own config file; the manifest points at these
 * exports instead (see `vite_module`, `vite_export`, `boot_export`,
 * `build_export` and `postcss_export` in docs-theme.json).
 *
 * This module sits at `<src>/.vitepress/theme/`, so the paths the plugins
 * need are one level up from `.vitepress`.
 */
let mediaColors: AkariMediaColorsPlugin | undefined;

function mediaColorsPlugin(): AkariMediaColorsPlugin {
  mediaColors ??= akariMediaColors({
    srcDir: fileURLToPath(new URL("../..", import.meta.url)),
    publicDir: fileURLToPath(new URL("../../public", import.meta.url)),
    cacheFile: fileURLToPath(new URL("../cache/media-colors.json", import.meta.url)),
  });
  return mediaColors;
}

export function akariVitePlugins(): Plugin[] {
  return [mediaColorsPlugin()];
}

/** The palette of the site's boot screen, derived from the theme seed. */
export function akariBootStylePlugins(seed?: string): AcceptedPlugin[] {
  return [akariBootColors(seed ? { seed } : {})];
}

/** Name of the build-time file that watches the boot screen. */
const BOOT_CONTROL_NAME = `boot-control.${createHash("sha256")
  .update(AKARI_BOOT_CONTROL_SCRIPT)
  .digest("hex")
  .slice(0, 10)}.js`;

function bootControlHref(base?: string): string {
  return `${base ?? "/"}assets/${BOOT_CONTROL_NAME}`;
}

/** The slice of VitePress's `transformHtml` context the boot needs. */
interface BootPageContext {
  pageData?: { frontmatter?: Record<string, unknown>; filePath?: string };
  siteConfig?: { site?: { base?: string } };
}

/**
 * The site's `transformHtml` hook: put the boot screen at the end of the body
 * and give a hero page the palette of its own image.
 *
 * The skeleton is pure HTML and CSS, so it paints before the control script
 * is fetched; that script only runs the fade-out and the retry button.
 */
export async function akariTransformHtml(
  html: string,
  _id: string,
  ctx?: BootPageContext,
): Promise<string> {
  const pageData = ctx?.pageData ?? {};
  const heroes = mediaColors ? await mediaColors.heroColors() : {};
  const palette = akariBootPageStyle(
    pageData.frontmatter ?? {},
    pageData.filePath ?? "",
    heroes,
  );
  return injectAkariBoot(html, bootControlHref(ctx?.siteConfig?.site?.base), palette);
}

/** What a build of the generated site does with images. */
export interface AkariBuildOptions {
  /** Convert the images the built pages use into WebP. Off by default. */
  webp?: boolean;
  /** Lossy quality, 1–100. Default 82. */
  quality?: number;
  /** Keep the originals beside their `.webp`. Default false. */
  keepOriginal?: boolean;
}

/**
 * The site's `buildEnd` hook: write the boot's control script next to the
 * built pages, then convert the images they point at.
 *
 * Only a build reaches this hook, so the dev server keeps serving the source
 * files. A generated config names this export (see `build_export` in
 * docs-theme.json) and passes the `webp` flag from its own config.
 */
export function akariBuildEnd(
  options: AkariBuildOptions = {},
): (site: BuiltSite) => Promise<void> {
  return async (site) => {
    await mkdir(join(site.outDir, "assets"), { recursive: true });
    await writeFile(join(site.outDir, "assets", BOOT_CONTROL_NAME), AKARI_BOOT_CONTROL_SCRIPT, "utf8");
    await akariMediaWebp({
      images: { webp: options.webp ?? false },
      quality: options.quality,
      keepOriginal: options.keepOriginal,
    })(site);
  };
}
